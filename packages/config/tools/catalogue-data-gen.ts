#!/usr/bin/env node
/**
 * T009 — the generator of `src/schema/catalogue-data.ts` (F110-FR-001,
 * F110-FR-009, F110-FR-010).
 *
 *     node packages/config/tools/catalogue-data-gen.ts            write the module
 *     node packages/config/tools/catalogue-data-gen.ts --check     compare with it
 *
 * `specs/110-config-and-terms/contracts/config-keys.tsv` is the contract that
 * task T004 derives from the tables of `spec.md` §K.3 to §K.6b. The product
 * cannot read that file at run time — it lives outside the published package —
 * so the catalogue ships as a TypeScript module inside `src/schema/`, one
 * entry per row, with the ten columns of the contract carried verbatim.
 *
 * Only the columns are copied here. Every reading of a column — the type and
 * its range, the default, the trust class, the snapshot class, the layers —
 * is done by `src/schema/type-parse.ts` and `src/schema/catalogue.ts`, so the
 * generated module holds no judgement that could drift from the product code.
 *
 * `--check` exits 1 when the module and the contract differ, and
 * `tests/unit/catalogue.test.ts` runs that comparison, so a key added to,
 * removed from or re-typed in the contract without the module following it
 * fails the build.
 *
 * It writes nothing outside `packages/config/src/schema/catalogue-data.ts`.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { COLUMNS, CATALOGUE_KEY_COUNT } from "./config-keys-gen.ts";

/** One row of the contract, as the generated module carries it. */
export interface RawCatalogueRow {
  readonly key: string;
  readonly type_and_range: string;
  readonly default: string;
  readonly value_under_parity: string;
  readonly trust_class: string;
  readonly owner_feature: string;
  readonly proposed_by: string;
  readonly confirmed_or_corrected: string;
  readonly layers: string;
  readonly profile_row: string;
}

/** Read the contract into rows. The header must be the ten columns of T004. */
export function parseTsv(text: string): RawCatalogueRow[] {
  const lines = text.split("\n").filter((l) => l !== "");
  const header = (lines[0] ?? "").split("\t");
  if (header.length !== COLUMNS.length || header.some((h, i) => h !== COLUMNS[i])) {
    throw new Error(
      `contracts/config-keys.tsv: the header is not the ten columns of T004: ${header.join(", ")}`,
    );
  }
  return lines.slice(1).map((line) => {
    const cells = line.split("\t");
    if (cells.length !== COLUMNS.length) {
      throw new Error(
        `contracts/config-keys.tsv: the row of \`${cells[0]}\` has ${cells.length} cells, ` +
          `not ${COLUMNS.length}`,
      );
    }
    const row: Record<string, string> = {};
    COLUMNS.forEach((c, i) => {
      row[c] = cells[i] ?? "";
    });
    return row as unknown as RawCatalogueRow;
  });
}

const quote = (s: string): string => JSON.stringify(s);

/** Render the module. */
export function renderModule(rows: readonly RawCatalogueRow[]): string {
  const body = rows
    .map((r) =>
      [
        "  {",
        `    key: ${quote(r.key)},`,
        `    typeAndRange: ${quote(r.type_and_range)},`,
        `    default: ${quote(r.default)},`,
        `    valueUnderParity: ${quote(r.value_under_parity)},`,
        `    trustClass: ${quote(r.trust_class)},`,
        `    ownerFeature: ${quote(r.owner_feature)},`,
        `    proposedBy: ${quote(r.proposed_by)},`,
        `    confirmedOrCorrected: ${quote(r.confirmed_or_corrected)},`,
        `    layers: ${quote(r.layers)},`,
        `    profileRow: ${quote(r.profile_row)},`,
        "  },",
      ].join("\n"),
    )
    .join("\n");
  return `/**
 * T009 — the catalogue of configuration keys as data (F110-FR-001,
 * F110-FR-009, F110-FR-010).
 *
 * GENERATED by \`packages/config/tools/catalogue-data-gen.ts\` from
 * \`specs/110-config-and-terms/contracts/config-keys.tsv\`, which task T004
 * derives from the tables of \`spec.md\` §K.3 to §K.6b. Do not edit by hand:
 * edit the tables, run T004's generator, then this one.
 * \`tests/unit/catalogue.test.ts\` fails when this module and the contract
 * differ.
 *
 * Each entry carries the cells of the contract verbatim. Every reading of a
 * cell happens in \`type-parse.ts\` and \`catalogue.ts\`.
 */

/** One row of \`contracts/config-keys.tsv\`, verbatim. */
export interface CatalogueDataRow {
  /** The exact spelling of the key (§K.1). */
  readonly key: string;
  /** The cell "Type and range". */
  readonly typeAndRange: string;
  /** The cell "Default". */
  readonly default: string;
  /** The cell "Under \`parity\`" of the contract. */
  readonly valueUnderParity: string;
  /** The cell "Class", with the snapshot class in parentheses. */
  readonly trustClass: string;
  /** The cell "Owner": the feature or features that own the meaning. */
  readonly ownerFeature: string;
  /** The features that proposed the key (T004). */
  readonly proposedBy: string;
  /** The decision of §K.9 for the key (T004). */
  readonly confirmedOrCorrected: string;
  /** The cell "Layers". */
  readonly layers: string;
  /** The row of annex X §X.7, or the empty string. */
  readonly profileRow: string;
}

/** The number of keys the catalogue holds (T004). */
export const CATALOGUE_SIZE = ${rows.length};

/** Every row of the catalogue, in the order of §K.3 to §K.6b. */
export const CATALOGUE_DATA: readonly CatalogueDataRow[] = Object.freeze([
${body}
]);
`;
}

/** Where the two files are. */
export interface Places {
  readonly tsv: string;
  readonly module: string;
}

export function defaultPlaces(): Places {
  const here = dirname(fileURLToPath(import.meta.url));
  const repo = join(here, "..", "..", "..");
  return {
    tsv: join(repo, "specs", "110-config-and-terms", "contracts", "config-keys.tsv"),
    module: join(here, "..", "src", "schema", "catalogue-data.ts"),
  };
}

/** The differences between the contract and the module, as lines. */
export function check(places: Places = defaultPlaces()): string[] {
  const rows = parseTsv(readFileSync(places.tsv, "utf8"));
  const problems: string[] = [];
  if (rows.length !== CATALOGUE_KEY_COUNT) {
    problems.push(
      `contracts/config-keys.tsv holds ${rows.length} keys, not ${CATALOGUE_KEY_COUNT} (T004)`,
    );
  }
  const wanted = renderModule(rows);
  let found = "";
  try {
    found = readFileSync(places.module, "utf8");
  } catch {
    problems.push(`src/schema/catalogue-data.ts is missing`);
    return problems;
  }
  if (found !== wanted) {
    const a = wanted.split("\n");
    const b = found.split("\n");
    for (let i = 0; i < Math.max(a.length, b.length); i += 1) {
      if (a[i] !== b[i]) {
        problems.push(
          `src/schema/catalogue-data.ts differs from the contract at line ${i + 1}: ` +
            `generated ${JSON.stringify(a[i] ?? "(end of file)")}, ` +
            `found ${JSON.stringify(b[i] ?? "(end of file)")}`,
        );
        if (problems.length > 10) break;
      }
    }
  }
  return problems;
}

/** Write the module from the contract. */
export function write(places: Places = defaultPlaces()): number {
  const rows = parseTsv(readFileSync(places.tsv, "utf8"));
  writeFileSync(places.module, renderModule(rows), "utf8");
  return rows.length;
}

function main(argv: string[]): number {
  if (argv.includes("--check")) {
    const problems = check();
    for (const p of problems) process.stdout.write(`${p}\n`);
    process.stdout.write(
      problems.length === 0
        ? "src/schema/catalogue-data.ts equals contracts/config-keys.tsv\n"
        : `${problems.length} difference(s)\n`,
    );
    return problems.length === 0 ? 0 : 1;
  }
  const n = write();
  process.stdout.write(`wrote src/schema/catalogue-data.ts: ${n} keys\n`);
  return 0;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  process.exit(main(process.argv.slice(2)));
}
