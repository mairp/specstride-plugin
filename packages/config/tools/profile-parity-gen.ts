#!/usr/bin/env node
/**
 * T010 — the generator of `data/profile-parity.json` (F110-FR-008, F110-FR-013).
 *
 *     node packages/config/tools/profile-parity-gen.ts            write the file
 *     node packages/config/tools/profile-parity-gen.ts --check     compare with it
 *
 * The profile is data (F100-FR-210): one row per switch of the schema, with the
 * value the switch has under `parity` or the reserved literal that says the
 * profile sets nothing for it. Both come from the catalogue, whose column
 * "Under `parity`" task T004 derives from the tables of §K.3 to §K.6b, so the
 * profile cannot disagree with the schema it belongs to.
 *
 * A switch of the schema is a key whose cell "Under `parity`" is not
 * `as default` (§K.1): a key that is not a switch has, under `parity`, the value
 * it has at the baseline, which is its default in the catalogue, so the profile
 * needs no row for it.
 *
 * The rows of annex X §X.7 that `@specstride/contracts` ships are joined in as
 * `annexRows` and `annexParity`, so that a reader sees both the resolved entry
 * and the prose of the annex the resolution came from. The annex stands where
 * the two differ ("Rows of the `parity` profile" of `spec.md`), which
 * `tests/unit/profile.test.ts` checks row by row.
 *
 * It writes nothing outside `packages/config/data/profile-parity.json`.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { profileRows } from "@specstride/contracts/profile/parity";

import { CATALOGUE } from "../src/schema/catalogue.ts";

/** The schema id of a profile (annex X §X.7). */
export const PROFILE_SCHEMA_ID = "specstride.profile/1";

/** The name of the profile this file ships. */
export const PROFILE_NAME = "parity";

/** One row of `data/profile-parity.json`. */
export interface ProfileParityRow {
  readonly key: string;
  readonly annexRows: readonly number[];
  readonly annexParity: readonly string[];
  readonly cell: string;
  readonly sets: boolean;
  readonly value?: unknown;
  readonly literal?: string;
  readonly default: string;
  readonly owners: readonly string[];
}

/** Build the rows from the catalogue. */
export function buildRows(): ProfileParityRow[] {
  return CATALOGUE.filter((e) => e.parity.kind !== "as-default").map((e) => {
    const annexParity = e.profileRows
      .map((n) => profileRows.find((r) => r.number === n)?.parity)
      .filter((p): p is string => p !== undefined);
    const common = {
      key: e.key,
      annexRows: e.profileRows,
      annexParity,
      cell: e.cells.valueUnderParity,
      default: e.cells.default,
      owners: e.owners,
    };
    if (e.parity.kind === "value") {
      return { ...common, sets: true, value: e.parity.value };
    }
    if (e.parity.kind === "literal") {
      return { ...common, sets: false, literal: e.parity.literal };
    }
    throw new Error(`the key \`${e.key}\` is not a switch and needs no row`);
  });
}

/** Render the file. */
export function renderJson(rows: readonly ProfileParityRow[]): string {
  const body = {
    schema: PROFILE_SCHEMA_ID,
    profile: PROFILE_NAME,
    note:
      "GENERATED by packages/config/tools/profile-parity-gen.ts from the catalogue " +
      "(specs/110-config-and-terms/contracts/config-keys.tsv, column value_under_parity) " +
      "joined with the rows of annex X §X.7 that @specstride/contracts ships. One row per " +
      "switch of the schema: `sets` true carries the value the switch takes under the " +
      "profile, `sets` false the reserved literal of closed set 239 that says the profile " +
      "leaves the key at its default. Do not edit by hand.",
    annex: "annex X §X.7",
    switchCount: rows.length,
    rows,
  };
  return `${JSON.stringify(body, null, 2)}\n`;
}

/** Where the file is. */
export function defaultPlace(): string {
  const here = dirname(fileURLToPath(import.meta.url));
  return join(here, "..", "data", "profile-parity.json");
}

/** The differences between the catalogue and the file, as lines. */
export function check(place: string = defaultPlace()): string[] {
  const wanted = renderJson(buildRows());
  let found = "";
  try {
    found = readFileSync(place, "utf8");
  } catch {
    return ["data/profile-parity.json is missing"];
  }
  if (found === wanted) return [];
  const a = wanted.split("\n");
  const b = found.split("\n");
  const problems: string[] = [];
  for (let i = 0; i < Math.max(a.length, b.length) && problems.length <= 10; i += 1) {
    if (a[i] !== b[i]) {
      problems.push(
        `data/profile-parity.json differs from the catalogue at line ${i + 1}: ` +
          `generated ${JSON.stringify(a[i] ?? "(end of file)")}, found ${JSON.stringify(b[i] ?? "(end of file)")}`,
      );
    }
  }
  return problems;
}

/** Write the file from the catalogue. */
export function write(place: string = defaultPlace()): number {
  const rows = buildRows();
  writeFileSync(place, renderJson(rows), "utf8");
  return rows.length;
}

function main(argv: string[]): number {
  if (argv.includes("--check")) {
    const problems = check();
    for (const p of problems) process.stdout.write(`${p}\n`);
    process.stdout.write(
      problems.length === 0
        ? "data/profile-parity.json equals the catalogue\n"
        : `${problems.length} difference(s)\n`,
    );
    return problems.length === 0 ? 0 : 1;
  }
  const n = write();
  process.stdout.write(`wrote data/profile-parity.json: ${n} switches\n`);
  return 0;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  process.exit(main(process.argv.slice(2)));
}
