/**
 * T041 — the integrity check of the launch bundle and the launcher
 * (F107-FR-031; C-224).
 *
 * The FOUR assertions, checked at EVERY start of the launcher, at the start
 * of the pipeline entry, and at the start of the runtime root:
 *
 *  1. the launcher's own content hash matches its marker (it was not edited);
 *  2. the manifest of the launch bundle hashes to the hash of the bundle the
 *     launcher names;
 *  3. every file of the bundle hashes to its manifest entry;
 *  4. the launch contract inside the bundle hashes to the contract hash the
 *     render recorded — the bundle address agrees with the contract.
 *
 * A failed assertion is a REFUSAL: exit 20 and ONE line on standard error,
 * naming the logical name of what failed. The check reads only; the response
 * of the pipeline is never its own proof.
 */
import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";

import { canonicalRecordText, contentHash } from "@specstride/kernel";

import { hasMarker, ownHashIsValid } from "../render/launcher.ts";
import { CONTRACT_FILE, MANIFEST_FILE, canonicalManifestBytes } from "../render/bundle.ts";

/** One refusal of the integrity check: exit 20, one line. */
export type IntegrityRefusal = {
  readonly exit: 20;
  /** The logical name (or the file) whose integrity failed. */
  readonly subject: string;
  readonly line: string;
};

function refusal(subject: string, line: string): IntegrityRefusal {
  return { exit: 20, subject, line: `integrity check failed for ${subject}: ${line}` };
}

/** The assertions of F107-FR-031, numbered for the report. */
export const INTEGRITY_ASSERTIONS: readonly string[] = Object.freeze([
  "the own-content hash of the launcher matches its marker",
  "the manifest of the bundle hashes to the hash of the bundle",
  "every file of the bundle hashes to its manifest entry",
  "the launch contract inside the bundle hashes to the contract hash of the render",
]);

/** The input of one integrity check. */
export type IntegrityInput = {
  readonly launcherFile?: string | undefined;
  readonly bundlePath: string;
  readonly bundleHash: string;
  readonly contractHash?: string | undefined;
  /** The bundle as a logical name, for the line of the refusal. */
  readonly bundleLogicalName?: string | undefined;
};

/** The single refusal the check found, or `undefined` when everything holds. */
export function integrityRefusal(input: IntegrityInput): IntegrityRefusal | undefined {
  const subject = input.bundleLogicalName ?? input.bundlePath;
  if (input.launcherFile !== undefined) {
    // Assertion 1: the launcher was not edited.
    if (!existsSync(input.launcherFile)) {
      return refusal(input.launcherFile, "the launcher is missing");
    }
    let text: string;
    try {
      text = readFileSync(input.launcherFile, "utf8");
    } catch {
      return refusal(input.launcherFile, "the launcher cannot be read");
    }
    if (!hasMarker(text)) {
      return refusal(input.launcherFile, "the launcher was not generated by contract render");
    }
    if (!ownHashIsValid(text)) {
      return refusal(input.launcherFile, "the launcher was edited after the render");
    }
  }
  // Assertion 2: the manifest hashes to the hash of the bundle.
  const manifestPath = join(input.bundlePath, MANIFEST_FILE);
  if (!existsSync(manifestPath)) {
    return refusal(subject, `the manifest is missing: ${MANIFEST_FILE}`);
  }
  let manifest: unknown;
  try {
    manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
  } catch {
    return refusal(subject, `the manifest is not JSON: ${MANIFEST_FILE}`);
  }
  if (contentHash(canonicalManifestBytes(manifest)) !== input.bundleHash) {
    return refusal(subject, "the manifest does not hash to the hash of the bundle");
  }
  // Assertion 3: every file of the bundle hashes to its manifest entry.
  const files = (manifest as { files?: unknown } | null)?.files;
  if (!Array.isArray(files)) return refusal(subject, "the manifest holds no file list");
  for (const entry of files as { path?: unknown; sha256?: unknown }[]) {
    if (typeof entry.path !== "string" || typeof entry.sha256 !== "string") {
      return refusal(subject, "the manifest holds a file entry without a path or a hash");
    }
    const full = join(input.bundlePath, entry.path);
    if (!existsSync(full))
      return refusal(subject, `a file of the bundle is missing: ${entry.path}`);
    if (contentHash(readFileSync(full)) !== entry.sha256) {
      return refusal(subject, `a file of the bundle changed: ${entry.path}`);
    }
  }
  // Assertion 4: the contract inside the bundle hashes to the contract hash.
  const contractPath = join(input.bundlePath, CONTRACT_FILE);
  if (!existsSync(contractPath)) {
    return refusal(subject, `the launch contract of the bundle is missing: ${CONTRACT_FILE}`);
  }
  if (input.contractHash !== undefined) {
    let contract: unknown;
    try {
      contract = JSON.parse(readFileSync(contractPath, "utf8"));
    } catch {
      return refusal(subject, "the launch contract of the bundle is not JSON");
    }
    const hash = contentHash(`${canonicalRecordText(contract)}\n`);
    if (hash !== input.contractHash) {
      return refusal(subject, "the launch contract changed after the render");
    }
  }
  return undefined;
}

/** The refusal at the start of the launcher (F107-FR-031: every start). */
export function launcherStartRefusal(input: IntegrityInput): string | undefined {
  return integrityRefusal(input)?.line;
}

/**
 * The refusal at the start of the pipeline entry: the same four assertions,
 * with the launcher verified beside the bundle.
 */
export function pipelineEntryRefusal(input: IntegrityInput): IntegrityRefusal | undefined {
  return integrityRefusal(input);
}

/**
 * The refusal at the start of the runtime root: the launcher and the bundle
 * are verified again at every relaunch (F107-FR-031), with the same four
 * assertions and no second reading of them.
 */
export function runtimeRootRefusal(input: IntegrityInput): IntegrityRefusal | undefined {
  return integrityRefusal(input);
}
