/**
 * T039 — the launcher (F107-FR-030; C-223) and the edited-launcher refusal
 * (F107-FR-028; C-220).
 *
 * The launcher is a file the operator can see and run: written atomically
 * with the mode `0755`, parent directory created, NOT a Bash script. It
 * starts with the interpreter line of the product's runtime (node), holds a
 * MARKER line that names the product, the renderer version and the hash of
 * the launch contract, and a line with the hash of the launcher's own text —
 * computed over the text with that hash replaced by a fixed placeholder.
 * Its body names the launch bundle by its logical name, which the product
 * resolves through the state layout, AND by the hash of the launch bundle,
 * and passes every argument through.
 *
 * A launcher is EDITED when its own content hash does not match its marker;
 * a file without the marker was NOT generated. Render refuses to overwrite
 * either, unless `--replace-edited` is given, and leaves the file unchanged.
 */
import { chmodSync, existsSync, mkdirSync, readFileSync } from "node:fs";
import { dirname } from "node:path";

import { contentHash } from "@specstride/kernel";

import { atomicWrite as writeAtomically } from "@specstride/kernel";
import {
  bundleStateName,
  contractStateName,
  launcherStateName,
  physicalPathOfLogicalName,
} from "../layout.ts";

/** The interpreter line of the product's runtime (F107-FR-030: not Bash). */
export const INTERPRETER_LINE = "#!/usr/bin/env node";

/** The renderer version the marker names. */
export const RENDERER_VERSION = "1.0";

/** The fixed placeholder the own-content hash is computed over. */
export const OWN_HASH_PLACEHOLDER = "SPECSTRIDE_LAUNCHER_OWN_SHA256_PLACEHOLDER";

/** The logical name of the pipeline the launcher starts, held by the body. */
export type LauncherInput = {
  readonly pipelineId: string;
  readonly contractHash: string;
  readonly contractLogicalName?: string | undefined;
  readonly bundleLogicalName: string;
  readonly bundleHash: string;
  readonly mode: "run" | "dry-run";
  readonly integrityModule?: string | undefined;
};

/** The marker line of a generated launcher (F107-FR-030). */
export function markerLine(input: Pick<LauncherInput, "contractHash">): string {
  return `// specstride launcher v${RENDERER_VERSION} contract=${input.contractHash}`;
}

/** The body of the launcher, with the own-hash line still holding the placeholder. */
export function launcherBody(input: LauncherInput): string {
  const contractName = input.contractLogicalName ?? contractStateName(input.pipelineId);
  return [
    INTERPRETER_LINE,
    markerLine(input),
    `// launcher-sha256: ${OWN_HASH_PLACEHOLDER}`,
    // The phrase `generated by specstride` is the marker the supervisor's
    // launcher resolution looks for (F123-FR-026); every comment of the file
    // is a JavaScript comment — the launcher is a file the operator can RUN
    // (F107-FR-030), so a `#` comment would be a syntax error outside the
    // shebang line.
    "// Generated by specstride contract render. Editing this file makes the next render refuse it.",
    'import { existsSync, readFileSync } from "node:fs";',
    'import { createRequire } from "node:module";',
    "const require_ = createRequire(import.meta.url);",
    `const contractLogicalName = ${JSON.stringify(contractName)};`,
    `const bundleLogicalName = ${JSON.stringify(input.bundleLogicalName)};`,
    `const bundleHash = ${JSON.stringify(input.bundleHash)};`,
    `const mode = ${JSON.stringify(input.mode)};`,
    "const args = process.argv.slice(2);",
    "const integrity = require_(process.env.SPECSTRIDE_LAUNCH_INTEGRITY_MODULE ?? " +
      JSON.stringify(
        input.integrityModule ?? "@specstride/pipeline/src/contract/launch/integrity.ts",
      ) +
      ");",
    "// The integrity check of F107-FR-031 runs at EVERY start of the launcher,",
    "// before anything else; a refusal is exit 20 and one line.",
    "const refusal = integrity.launcherStartRefusal({",
    "  launcherFile: process.env.SPECSTRIDE_LAUNCHER_FILE ?? import.meta.filename,",
    "  bundlePath: process.env.SPECSTRIDE_BUNDLE_PATH,",
    "  bundleHash,",
    "});",
    "if (refusal !== undefined) {",
    "  process.stderr.write(`launcher: ${refusal}\\n`);",
    "  process.exit(20);",
    "}",
    'const pipeline = require_(process.env.SPECSTRIDE_PIPELINE_ENTRY ?? "@specstride/pipeline/src/entry.ts");',
    "pipeline.main({ bundleLogicalName, bundleHash, mode, args });",
    "",
  ].join("\n");
}

/** The full launcher text: the own-content hash in place of the placeholder. */
export function launcherText(input: LauncherInput): string {
  const withPlaceholder = launcherBody(input);
  const ownHash = contentHash(withPlaceholder);
  return withPlaceholder.replace(OWN_HASH_PLACEHOLDER, ownHash);
}

/** The own-content hash of a launcher file, or `undefined` without the marker. */
export function ownHashOf(launcherText: string): string | undefined {
  const line = launcherText.split("\n").find((one) => one.startsWith("// launcher-sha256: "));
  if (line === undefined) return undefined;
  return line.slice("// launcher-sha256: ".length).trim();
}

/** The hash of the launcher's own text, computed over the placeholder form. */
export function ownHashIsValid(launcherText: string): boolean {
  const recorded = ownHashOf(launcherText);
  if (recorded === undefined) return false;
  return contentHash(launcherText.replace(recorded, OWN_HASH_PLACEHOLDER)) === recorded;
}

/** True when the text of a launcher file carries the marker of the product. */
export function hasMarker(text: string): boolean {
  return text.split("\n").some((one) => one.startsWith("// specstride launcher v"));
}

/** Why a launcher at a path must not be overwritten (F107-FR-028). */
export type LauncherState =
  | { readonly state: "absent" }
  | { readonly state: "generated"; readonly intact: boolean }
  | { readonly state: "not-generated" }
  | { readonly state: "edited" };

/** Read the state of a launcher file, without judging it (F107-FR-028). */
export function launcherStateAt(path: string): LauncherState {
  if (!existsSync(path)) return { state: "absent" };
  let text: string;
  try {
    text = readFileSync(path, "utf8");
  } catch {
    return { state: "not-generated" };
  }
  if (!hasMarker(text)) return { state: "not-generated" };
  return { state: "generated", intact: ownHashIsValid(text) };
}

/** The refusal of an existing launcher at the path, when render must refuse. */
export function editedLauncherRefusal(path: string, replaceEdited: boolean): string | undefined {
  const state = launcherStateAt(path);
  if (state.state === "absent") return undefined;
  if (state.state === "generated" && state.intact) return undefined;
  if (replaceEdited) return undefined;
  return `refusing to replace edited or non-generated launcher: ${path}; choose another path or pass --replace-edited explicitly`;
}

/**
 * Write the launcher: atomically, with the mode `0755`, parent directory
 * created (F107-FR-030).
 */
export function writeLauncher(path: string, text: string): string {
  mkdirSync(dirname(path), { recursive: true });
  writeAtomically(path, text, { createDirectory: true, mode: 0o755 });
  // The mode is part of the artifact: set it after the rename, so a launcher
  // that replaced a file keeps `0755` even where the temporary inherited one.
  chmodSync(path, 0o755);
  return path;
}

