/**
 * T043 — `supervise resolve`: the launcher resolution and its five refusals
 * (F123-FR-026).
 *
 * The launcher is found in this order: the requested path (relative to the
 * repository); the default launcher of the feature; the single file in the
 * repository whose first 400 bytes carry the marker of generated launchers —
 * skipping the version-control directory, links, and the directories of
 * generated bundles and of pipeline runs. The verb prints the launcher line,
 * or refuses with `launcher-not-found`, `launcher-missing` or
 * `launcher-ambiguous`, and refuses with `launcher-unreadable` or
 * `launcher-not-generated` when the launch bundle cannot be read from the
 * launcher. Every refusal prints the same next step and exits 4.
 */
import { existsSync, readdirSync, readFileSync, statSync } from "node:fs";
import { isAbsolute, join, relative, resolve } from "node:path";
import { resolveRefusals } from "@specstride/contracts";

/** The five refusals of `resolve` (closed set, row 101). */
export const RESOLVE_REFUSALS = resolveRefusals;

/** The text a generated launcher carries in its first 400 bytes. */
export const GENERATED_MARKER = "generated by specstride";

/** The first slice of the file the marker is looked for in. */
export const MARKER_WINDOW_BYTES = 400 as const;

/** The next step every refusal of `resolve` prints. */
export const RESOLVE_NEXT = "ask for `auto` to generate the launcher first";

/** The exit code of a refusal of `resolve`. */
export const RESOLVE_REFUSAL_EXIT = 4 as const;

/** The sources the launcher line names. */
export type LauncherSource = "request" | "feature-default" | "generated-marker";

/** The result of the resolution: a launcher, or a named refusal. */
export type ResolveResult =
  | { readonly ok: true; readonly launcher: string; readonly source: LauncherSource }
  | { readonly ok: false; readonly refusal: string; readonly next: string };

/** The directory names the walk of the repository skips. */
export const SKIPPED_DIRECTORIES: readonly string[] = Object.freeze([
  ".git",
  "node_modules",
  ".specstride-bundles",
  "runs",
  ".run",
]);

/** True when the first 400 bytes of the file carry the generated marker. */
export function carriesGeneratedMarker(path: string): boolean {
  const handle = readFileSync(path);
  const head = handle.subarray(0, MARKER_WINDOW_BYTES).toString("utf8");
  return head.includes(GENERATED_MARKER);
}

/** Refuse with a literal and the fixed next step. */
function refusal(kind: string): ResolveResult {
  return { ok: false, refusal: kind, next: RESOLVE_NEXT };
}

/** Step 1 — the requested path, relative to the repository. */
function fromRequest(repoDir: string, requested: string | undefined): ResolveResult | null {
  if (requested === undefined) return null;
  const path = isAbsolute(requested) ? requested : resolve(repoDir, requested);
  if (!existsSync(path)) return refusal("launcher-not-found");
  return { ok: true, launcher: path, source: "request" };
}

/** Step 2 — the default launcher of the feature. */
function fromFeatureDefault(repoDir: string, feature: string | undefined): ResolveResult | null {
  if (feature === undefined) return null;
  const path = join(repoDir, ".specstride", "launchers", `${feature}.mjs`);
  if (!existsSync(path)) return refusal("launcher-missing");
  return { ok: true, launcher: path, source: "feature-default" };
}

/** Walk one directory for generated launchers; links and skipped directories are never entered. */
function walkForGenerated(dir: string, found: string[], depth: number): void {
  if (depth > 8 || found.length > 1) return;
  let entries: string[];
  try {
    entries = readdirSync(dir);
  } catch {
    return;
  }
  for (const entry of entries) {
    if (SKIPPED_DIRECTORIES.includes(entry)) continue;
    const path = join(dir, entry);
    let stats;
    try {
      stats = statSync(path, { throwIfNoEntry: false });
    } catch {
      continue;
    }
    if (stats === undefined) continue;
    if (stats.isSymbolicLink()) continue;
    if (stats.isDirectory()) {
      walkForGenerated(path, found, depth + 1);
    } else if (stats.isFile() && carriesGeneratedMarker(path)) {
      found.push(path);
      if (found.length > 1) return;
    }
  }
}

/** Step 3 — the single generated launcher in the repository. */
function fromGeneratedMarker(repoDir: string): ResolveResult {
  const found: string[] = [];
  walkForGenerated(repoDir, found, 0);
  if (found.length === 0) return refusal("launcher-not-found");
  if (found.length > 1) return refusal("launcher-ambiguous");
  return { ok: true, launcher: found[0] as string, source: "generated-marker" };
}

/**
 * Resolve the launcher in the order of F123-FR-026. The repository directory
 * anchors every relative path; the walk skips the version-control directory,
 * links, and the directories of generated bundles and of pipeline runs.
 */
export function resolveLauncher(input: {
  repoDir: string;
  feature?: string;
  requested?: string;
}): ResolveResult {
  const repoDir = resolve(input.repoDir);
  const byRequest = fromRequest(repoDir, input.requested);
  if (byRequest !== null) return byRequest;
  const byDefault = fromFeatureDefault(repoDir, input.feature);
  if (byDefault !== null) return byDefault;
  return fromGeneratedMarker(repoDir);
}

/**
 * Read the launch bundle from the launcher. Refuses with
 * `launcher-unreadable` when the launcher cannot be read and with
 * `launcher-not-generated` when it does not carry the marker.
 */
export function readLaunchBundle(launcherPath: string): { ok: true; text: string } | ResolveResult {
  let text: string;
  try {
    text = readFileSync(launcherPath, "utf8");
  } catch {
    return refusal("launcher-unreadable");
  }
  if (!text.slice(0, MARKER_WINDOW_BYTES).includes(GENERATED_MARKER)) {
    return refusal("launcher-not-generated");
  }
  return { ok: true, text };
}

/** The path of the launcher as the launcher line prints it: relative to the repository. */
export function displayPath(repoDir: string, launcherPath: string): string {
  const rel = relative(resolve(repoDir), resolve(launcherPath));
  return rel === "" ? launcherPath : rel;
}
